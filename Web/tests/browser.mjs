import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const baseURL = process.env.BASE_URL || 'http://127.0.0.1:4173';
const artifactDirectory = resolve(process.env.QA_ARTIFACT_DIR || fileURLToPath(new URL('../artifacts/', import.meta.url)));
const artifact = name => join(artifactDirectory, name);
await mkdir(artifactDirectory, { recursive: true });
console.log('Starting browser verification:', baseURL);
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE_PATH || undefined, headless: true, timeout: 45000, args: ['--no-sandbox', '--disable-dev-shm-usage', '--disable-gpu', '--renderer-process-limit=1'] });
let context;
const errors = [];
try {
  context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'ru-RU' });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const response = await page.goto(baseURL, { waitUntil: 'networkidle' });
  assert.equal(response.status(), 200);
  await page.waitForSelector('#target-height');
  assert.equal(await page.locator('#target-height').textContent(), '650');
  console.log('Desktop calculator loaded');
  await page.screenshot({ path: artifact('desktop.png'), fullPage: true });
  await page.locator('#toggle-lensEnabled').check();
  await page.locator('#field-lensSetback').fill('100');
  assert.equal(await page.locator('#target-height').textContent(), '649');
  assert.match(await page.locator('#lens-explanation').textContent(), /5000 \+ 100 = 5100 мм/);
  await page.locator('#toggle-horizontal').check();
  await page.locator('#field-rightFront').fill('5140');
  await page.locator('#field-rearSide').fill('1700');
  assert.equal(await page.locator('input[name="cornerSource"][value="headlights"]').isChecked(), true);
  assert.equal(await page.locator('#field-bumperFront').isVisible(), false);
  await page.locator('#toggle-measureCorner').check();
  assert.match(await page.locator('#angle-comparison').textContent(), /95,74°/);
  assert.match(await page.locator('#angle-comparison').textContent(), /Разница: 5,74°/);
  await page.locator('#field-triangleDiagonal').fill('9000');
  assert.equal(await page.locator('#error-card').isVisible(), false);
  assert.match(await page.locator('#angle-comparison').textContent(), /не существует/);
  await page.locator('input[name="cornerSource"][value="triangle"]').check();
  assert.equal(await page.locator('#error-card').isVisible(), true);
  await page.locator('#field-triangleDiagonal').fill('5000');
  await page.locator('#field-bumperFront').fill('');
  assert.equal(await page.locator('#error-card').isVisible(), true);
  await page.locator('input[name="cornerSource"][value="headlights"]').check();
  assert.equal(await page.locator('#error-card').isVisible(), false);
  await page.locator('input[name="cornerSource"][value="triangle"]').check();
  await page.locator('#field-bumperFront').fill('4800');
  await page.locator('#field-rearSide').fill('1250');
  assert.equal(await page.locator('#target-height').textContent(), '648,7');
  assert.match(await page.locator('#horizontal-result').textContent(), /1478,9 мм/);
  assert.match(await page.locator('#horizontal-result').textContent(), /512,6 мм вправо/);
  await page.locator('[data-diagram="plan"]').click();
  assert.equal(await page.locator('#beam-diagram svg').count(), 1);
  assert.ok((await page.locator('.topbar').boundingBox()).y >= 0, 'Desktop header remains visible while editing');
  assert.equal(await page.evaluate(() => document.documentElement.scrollHeight > innerHeight + 1), false);
  await page.screenshot({ path: artifact('desktop-geometry.png'), fullPage: true });
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('input[name="cornerSource"][value="triangle"]').isChecked(), true);
  assert.equal(await page.locator('#field-lensSetback').inputValue(), '100');
  assert.equal(await page.locator('#field-rightFront').inputValue(), '5140');
  assert.equal(await page.locator('#target-height').textContent(), '648,7');
  await page.pdf({ path: artifact('calculation.pdf'), format: 'A4', printBackground: true, preferCSSPageSize: true });
  await page.locator('#field-triangleDiagonal').fill('9000');
  assert.equal(await page.locator('#error-card').isVisible(), true);
  assert.match(await page.locator('#calculation-error').textContent(), /треугольника/);
  assert.equal(await page.locator('#print').isDisabled(), true);
  await page.locator('#field-triangleDiagonal').fill('5000');
  await page.locator('input[name="side"][value="right"]').check();
  await page.locator('#field-leftFront').fill('5140');
  await page.locator('#field-rightFront').fill('5000');
  assert.match(await page.locator('#horizontal-result').textContent(), /2885,9 мм/);
  assert.match(await page.locator('#horizontal-result').textContent(), /влево/);
  await page.locator('[data-nav="preparation"]').click();
  await page.locator('#check-0').check();
  assert.match(await page.locator('#checklist-progress').textContent(), /1 из 5/);
  await page.locator('[data-nav="guide"]').click();
  assert.equal(await page.locator('#guide').isVisible(), true);
  await page.locator('[data-nav="calculator"]').click();
  await page.locator('#reset').click();
  assert.equal(await page.locator('#target-height').textContent(), '650');
  assert.equal(await page.locator('#geometry-card').isVisible(), false);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await context.close(); context = null;
  console.log('Desktop interactions and PDF passed');

  context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1, hasTouch: true, locale: 'ru-RU' });
  const mobile = await context.newPage();
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto(baseURL, { waitUntil: 'networkidle' });
  assert.equal(await mobile.locator('#target-height').textContent(), '650');
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await mobile.screenshot({ path: artifact('mobile.png'), fullPage: true });
  await mobile.locator('#toggle-horizontal').check();
  await mobile.locator('#toggle-lensEnabled').check();
  await mobile.locator('#field-lensSetback').fill('100');
  await mobile.locator('#field-rightFront').fill('5140');
  await mobile.locator('#field-rearSide').fill('1250');
  await mobile.locator('#toggle-measureCorner').check();
  assert.match(await mobile.locator('#angle-comparison').textContent(), /Разница: 5,74°/);
  await mobile.locator('input[name="cornerSource"][value="triangle"]').check();
  assert.equal(await mobile.locator('#target-height').textContent(), '648,7');
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await mobile.locator('[data-diagram="plan"]').click();
  await mobile.screenshot({ path: artifact('mobile-geometry.png'), fullPage: true });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ status: 'passed', baseURL, desktop: '1440×1000', mobile: '390×844', pdf: artifact('calculation.pdf'), scenarios: ['defaults', 'lens', 'yaw', 'wall triangle', 'right wall', 'validation', 'persistence', 'checklist', 'navigation', 'responsive layout', 'corner method selector', 'independent comparison', 'PDF'] }));
} finally {
  if (context) await context.close();
  await browser.close();
}
